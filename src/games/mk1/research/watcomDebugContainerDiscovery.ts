function toHex32(val: number): string {
  return '0x' + (val >>> 0).toString(16).padStart(8, '0').toUpperCase();
}

/**
 * Computes SHA-256 hash using standard Web Crypto API if available.
 * Returns lowercase hex string, or null if unavailable.
 */
export async function computeSha256(bytes: Uint8Array): Promise<string | null> {
  try {
    if (typeof globalThis !== 'undefined' && globalThis.crypto?.subtle) {
      const hashBuffer = await globalThis.crypto.subtle.digest(
        'SHA-256',
        bytes.byteOffset === 0 && bytes.byteLength === bytes.buffer.byteLength
          ? bytes.buffer
          : bytes.slice().buffer,
      );
      const hashArray = Array.from(new Uint8Array(hashBuffer));
      return hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
    }
    return null;
  } catch {
    return null;
  }
}

/**
 * Report generated by MK1 Watcom Debug Container Discovery (Pass 1E.3A.1)
 */
export interface MK1WatcomDebugDiscoveryReport {
  format: 'mk1_watcom_debug_container_discovery_v1';
  timestamp: string;
  operationId: string;
  provenance: FixtureProvenance;
  fixture: {
    exePath: string;
    exeSize: number;
    exeSizeHex: string;
    highestFileBackedPageEnd: number;
    highestFileBackedPageEndHex: string;
    postModuleTail: {
      startOffset: number;
      startOffsetHex: string;
      endOffset: number;
      endOffsetHex: string;
      byteLength: number;
    };
  };
  discovery: WatcomDebugContainerDiscovery;
  epistemicInvariants: string[];
}

/**
 * Executes Pass 1E.3A.1 Watcom debug tail discovery and boundary qualification blindly against MK1.EXE.
 * Production orchestrator always reads executable bytes directly from DirectorySource.
 * Strictly respects research boundaries: no Mortal Kombat symbol searches, format qualification only.
 */
export async function discoverMK1WatcomDebugContainer(
  source: DirectorySource,
  options?: {
    exePath?: string;
  },
): Promise<MK1WatcomDebugDiscoveryReport> {
  return executeWatcomDebugDiscovery(source, options?.exePath);
}

/**
 * Internal/test-only orchestrator for synthetic test fixtures.
 * Gated: strictly throws if source is not synthetic.
 */
export async function discoverMK1WatcomDebugContainerForTest(
  source: DirectorySource,
  testOptions?: {
    exePath?: string;
    layoutReport?: MK1ExecutableLayoutReport;
  },
): Promise<MK1WatcomDebugDiscoveryReport> {
  if (!source.isSynthetic) {
    throw new Error('discoverMK1WatcomDebugContainerForTest cannot be invoked on non-synthetic source');
  }
  return executeWatcomDebugDiscovery(source, testOptions?.exePath, testOptions?.layoutReport);
}

async function executeWatcomDebugDiscovery(
  source: DirectorySource,
  customExePath?: string,
  injectedLayoutReport?: MK1ExecutableLayoutReport,
): Promise<MK1WatcomDebugDiscoveryReport> {
  const opId = createOperationId();
  const exePath = customExePath || 'MK1.EXE';

  logStageCheckpoint('research-mk1', 'watcom-debug-discovery', opId, 'start', {
    exePath,
  });

  try {
    if (injectedLayoutReport && !source.isSynthetic) {
      throw new Error('External layout report injection is prohibited on non-synthetic source');
    }

    // 1. Probe executable layout to resolve authoritative LE module topology
    const layoutReport =
      injectedLayoutReport || (await probeMK1ExecutableLayout(source, { exePath }));
    const postModuleTail = layoutReport.topology.postModuleTail;
    const highestFileBackedPageEnd =
      layoutReport.topology.boundaries?.highestFileBackedPageEnd ??
      (postModuleTail ? postModuleTail.startOffset - 1 : 0);
    const exeSize = layoutReport.exeSize;

    // 2. Obtain executable binary bytes directly from the supplied DirectorySource
    const slice = await source.readSlice(exePath, 0, exeSize);
    if (!slice || slice.length !== exeSize) {
      throw new Error(
        `Unable to read full ${exePath} (${exeSize} bytes) from source: discovery fails closed.`,
      );
    }
    const bytes = slice;

    const reader = new BinaryReader(bytes);

    // 3. Establish provenance strictly from the DirectorySource
    const isSyntheticSource = source.isSynthetic;

    let provenance: FixtureProvenance;
    if (isSyntheticSource) {
      provenance = {
        sourceKind: 'in-memory-buffer',
        fileName: exePath,
        byteLength: exeSize,
        sha256: null,
        synthetic: true,
        artifactGeneratedByTest: true,
        timestamp: new Date().toISOString(),
        operationId: opId,
      };
    } else {
      const sha256 = await computeSha256(bytes);
      provenance = {
        sourceKind: 'user-loaded-directory',
        fileName: exePath,
        byteLength: exeSize,
        sha256,
        synthetic: false,
        artifactGeneratedByTest: false,
        timestamp: new Date().toISOString(),
        operationId: opId,
      };
    }

    // 4. Run generic Watcom debug detector blindly against binary with tail hints
    const detectionOptions: WatcomDebugDetectionOptions = {
      postModuleTailStart: postModuleTail.startOffset,
      postModuleTailEnd: postModuleTail.endOffset,
    };

    const discovery = detectWatcomDebugContainer(reader, detectionOptions);

    logInfo(
      'research-mk1',
      'watcom-debug-discovery',
      opId,
      `Watcom debug container discovery completed with status: ${discovery.status} (format: ${discovery.format})`,
      {
        status: discovery.status,
        format: discovery.format,
        containerStart: discovery.containerPhysicalStartHex,
        containerEnd: discovery.containerPhysicalEndHex,
        byteLength: discovery.containerByteLength,
        sectionsCount: discovery.sectionCount,
      },
    );

    const report: MK1WatcomDebugDiscoveryReport = {
      format: 'mk1_watcom_debug_container_discovery_v1',
      timestamp: new Date().toISOString(),
      operationId: opId,
      provenance,
      fixture: {
        exePath,
        exeSize,
        exeSizeHex: toHex32(exeSize),
        highestFileBackedPageEnd,
        highestFileBackedPageEndHex: toHex32(highestFileBackedPageEnd),
        postModuleTail: {
          startOffset: postModuleTail.startOffset,
          startOffsetHex: toHex32(postModuleTail.startOffset),
          endOffset: postModuleTail.endOffset,
          endOffsetHex: toHex32(postModuleTail.endOffset),
          byteLength: postModuleTail.byteLength,
        },
      },
      discovery,
      epistemicInvariants: [
        'FORMAT DISCOVERY ONLY != SYMBOL ENUMERATION',
        'CONTAINER DETECTED != MORTAL KOMBAT SYMBOL VERIFIED',
        'SECTIONS DISCOVERED != CALL TARGET RESOLVED',
        'NO MK SYMBOL SEARCHES PERFORMED IN 1E.3A.1',
        'OPEN WATCOM SPECIFICATION != OBSERVED FIXTURE BYTES',
        'AUTHORITATIVE EVIDENCE REQUIRES REAL USER-LOADED DIRECTORY SOURCE',
      ],
    };

    logStageCheckpoint('research-mk1', 'watcom-debug-discovery', opId, 'complete', {
      status: report.discovery.status,
    });

    return report;
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    logError('research-mk1', 'watcom-debug-discovery', opId, err, { exePath });
    throw new Error(`Watcom debug container discovery failed: ${msg}`);
  }
}

/**
 * Creates the exportable JSON object for MK1 Watcom Debug Container Discovery (Pass 1E.3A.1).
 * Strictly gated by provenance safeguards: synthetic fixtures, test runners, or relabeled objects are rejected.
 */
export function createMK1WatcomDebugDiscoveryExport(
  report: MK1WatcomDebugDiscoveryReport,
): object {
  const prov = report.provenance;
  if (!prov) {
    throw new Error('Missing fixture provenance: cannot export research artifact without provenance');
  }

  // Provenance safeguards
  if (prov.synthetic) {
    throw new Error('Synthetic fixtures cannot generate authoritative research artifacts');
  }
  if (prov.artifactGeneratedByTest) {
    throw new Error('Tests cannot generate authoritative research artifacts');
  }
  if (prov.sourceKind !== 'user-loaded-directory') {
    throw new Error(
      `Invalid fixture provenance sourceKind: ${prov.sourceKind}. Must originate from user-loaded directory.`,
    );
  }
  if (!prov.sha256 || !/^[0-9a-f]{64}$/.test(prov.sha256)) {
    throw new Error('Authoritative export requires valid 64-character lowercase SHA-256 hex digest');
  }
  if (prov.byteLength !== report.fixture.exeSize) {
    throw new Error(
      `Provenance byte length (${prov.byteLength}) does not match report executable size (${report.fixture.exeSize})`,
    );
  }
  if (prov.operationId !== report.operationId) {
    throw new Error(
      `Provenance operation ID (${prov.operationId}) does not match report operation ID (${report.operationId})`,
    );
  }

  const d = report.discovery;
  const topology = report.fixture;

  return {
    format: report.format,
    timestamp: prov.timestamp || report.timestamp,
    operationId: prov.operationId || report.operationId,
    epistemicPolicy: [
      'AUTHORITATIVE REAL-FIXTURE RESEARCH EVIDENCE',
      'ORIGINATES EXCLUSIVELY FROM USER-LOADED DIRECTORY SOURCE',
      'NO SYNTHETIC DATA MASQUERADING AS FIXTURE EVIDENCE',
      'OBSERVED FIXTURE BYTES ARE AUTHORITATIVE OVER EXTERNAL SPECIFICATIONS',
      'NO MORTAL KOMBAT SYMBOL ENUMERATION PERFORMED IN 1E.3A.1',
    ],
    provenance: {
      sourceKind: prov.sourceKind,
      fileName: prov.fileName,
      byteLength: prov.byteLength,
      sha256: prov.sha256,
      synthetic: false,
      artifactGeneratedByTest: false,
      timestamp: prov.timestamp,
      operationId: prov.operationId,
    },
    executableTopology: {
      exePath: topology.exePath,
      exeSize: topology.exeSize,
      exeSizeHex: topology.exeSizeHex,
      highestFileBackedPageEnd: topology.highestFileBackedPageEnd,
      highestFileBackedPageEndHex: topology.highestFileBackedPageEndHex,
      postModuleTail: {
        startOffset: topology.postModuleTail.startOffset,
        startOffsetHex: topology.postModuleTail.startOffsetHex,
        endOffset: topology.postModuleTail.endOffset,
        endOffsetHex: topology.postModuleTail.endOffsetHex,
        byteLength: topology.postModuleTail.byteLength,
      },
    },
    watcomDiscovery: {
      status: d.status,
      format: d.format,
      candidateCount: d.candidateCount ?? (d.status === 'DETECTED' ? 1 : 0),
      selectedCandidate: d.masterHeader
        ? {
            physicalOffset: d.masterHeader.headerOffset,
            physicalOffsetHex: d.masterHeader.headerOffsetHex,
            exactBoundedBytesHex: d.masterHeader.rawBytesHex ?? null,
            exactBoundedBytes: d.masterHeader.rawBytes ?? null,
            parsedVersionFields: {
              exeMajorVer: d.masterHeader.exeMajorVer,
              exeMinorVer: d.masterHeader.exeMinorVer,
              objMajorVer: d.masterHeader.objMajorVer,
              objMinorVer: d.masterHeader.objMinorVer,
              versionString: d.masterHeader.versionString,
              versionValid: d.masterHeader.versionValid,
            },
            langSize: d.masterHeader.langSize,
            langSizeHex: d.masterHeader.langSizeHex,
            segmentSize: d.masterHeader.segmentSize,
            segmentSizeHex: d.masterHeader.segmentSizeHex,
            debugSize: d.masterHeader.debugSize,
            debugSizeHex: d.masterHeader.debugSizeHex,
            containerPhysicalStart: d.containerPhysicalStart,
            containerPhysicalStartHex: d.containerPhysicalStartHex,
            containerPhysicalEnd: d.containerPhysicalEnd,
            containerPhysicalEndHex: d.containerPhysicalEndHex,
            containerByteLength: d.containerByteLength,
          }
        : null,
      resourceTrailersBypassed: d.resourceTrailersBypassed,
    },
    tables: {
      languageTable: {
        startOffset: d.langTableStart,
        startOffsetHex: d.langTableStartHex,
        byteLength: d.langTableByteLength,
        rawBoundedBytesHex: d.langTableRawBytesHex ?? null,
      },
      segmentAddressTable: {
        startOffset: d.segmentTableStart,
        startOffsetHex: d.segmentTableStartHex,
        byteLength: d.segmentTableByteLength,
        rawBoundedBytesHex: d.segmentTableRawBytesHex ?? null,
      },
    },
    sectionStructure: {
      sectionsRegionStart: d.sectionsStart,
      sectionsRegionStartHex: d.sectionsStartHex,
      sectionsRegionByteLength: d.sectionsByteLength,
      sectionCount: d.sectionCount,
      allSectionsValid: d.allSectionsValid,
      tilingValid: d.tilingValid,
      sections: d.sections.map((s: WatcomSectionDebugHeader) => ({
        sectionIndex: s.sectionIndex,
        fileOffset: s.fileOffset,
        fileOffsetHex: s.fileOffsetHex,
        exactBoundedHeaderBytesHex: s.rawBytesHex ?? null,
        exactBoundedHeaderBytes: s.rawBytes ?? null,
        decodedOffsets: {
          modOffset: s.modOffset,
          modOffsetHex: s.modOffsetHex,
          gblOffset: s.gblOffset,
          gblOffsetHex: s.gblOffsetHex,
          addrOffset: s.addrOffset,
          addrOffsetHex: s.addrOffsetHex,
        },
        sectionSize: s.sectionSize,
        sectionSizeHex: s.sectionSizeHex,
        sectionId: s.sectionId,
        isPlacekeeper: s.isPlacekeeper,
        valid: s.valid,
        validationError: s.validationError || null,
      })),
    },
    unresolvedRegions: {
      unresolvedPreDebugTail: d.unresolvedPreDebugTail ?? {
        startOffset: topology.postModuleTail.startOffset,
        startOffsetHex: topology.postModuleTail.startOffsetHex,
        endOffset: d.containerPhysicalStart ?? topology.postModuleTail.startOffset,
        endOffsetHex: d.containerPhysicalStartHex ?? topology.postModuleTail.startOffsetHex,
        byteLength: Math.max(
          0,
          (d.containerPhysicalStart ?? topology.postModuleTail.startOffset) -
            topology.postModuleTail.startOffset,
        ),
        classification: 'UNKNOWN POST-MODULE / PRE-DEBUG DATA',
        notes:
          'Bytes preceding the validated Watcom debug container remain UNKNOWN. No purpose is inferred.',
      },
    },
    validationChecks: d.validationChecks.map((c: WatcomDebugValidationCheck) => ({
      checkId: c.checkId,
      name: c.name,
      passed: c.passed,
      detail: c.detail,
    })),
    tailCorrelation: d.tailCorrelation ?? null,
  };
}

/**
 * Non-authoritative serializer for test inspection or in-memory validation.
 * Unlike createMK1WatcomDebugDiscoveryExport, this does not certify real-fixture provenance
 * and explicitly tags output with nonAuthoritative: true.
 */
export function serializeWatcomDiscoveryNonAuthoritative(
  report: MK1WatcomDebugDiscoveryReport,
): object {
  const d = report.discovery;
  const topology = report.fixture;

  return {
    format: report.format,
    timestamp: report.timestamp,
    operationId: report.operationId,
    nonAuthoritative: true,
    provenance: report.provenance,
    executableTopology: {
      exePath: topology.exePath,
      exeSize: topology.exeSize,
      exeSizeHex: topology.exeSizeHex,
    },
    watcomDiscovery: {
      status: d.status,
      format: d.format,
    },
  };
}
